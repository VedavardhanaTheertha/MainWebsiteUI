import { access, mkdir, readFile, rm, writeFile } from "node:fs/promises";
import { gzipSync } from "node:zlib";
import path from "node:path";
import { fileURLToPath } from "node:url";
import MiniSearch from "minisearch";
import { collection } from "./collection.config.mjs";
import {
  buildSearchText,
  removeSearchTags,
  splitSongContent,
  validateMetadata,
} from "./content-utils.mjs";
import { renderMarkdown } from "./markdown.mjs";

const projectRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const libraryRoot = path.join(projectRoot, "library");
const dataRoot = path.join(projectRoot, "src", "gen");
const previousCollectionRoot = path.join(dataRoot, "dasasahitya");
const previousGeneratedRoot = path.join(projectRoot, "src", "generated-content");
const legacyGeneratedRoot = path.join(projectRoot, "src", "generated");
const legacyDataRoot = path.join(projectRoot, "website-data");

async function buildCollection({ id, sourceDirectory }) {
  const collectionOutput = path.join(dataRoot, id);
  await mkdir(collectionOutput, { recursive: true });

  const sourceRoot = path.join(libraryRoot, sourceDirectory);
  const metadataPath = path.join(sourceRoot, "metadata.json");
  try {
    await access(metadataPath);
  } catch {
    throw new Error(
      `Required library content is missing at ${path.relative(projectRoot, metadataPath)}. ` +
        "Initialize submodules with: git submodule update --init --recursive",
    );
  }

  const metadata = JSON.parse(await readFile(metadataPath, "utf8"));
  validateMetadata(metadata, id);

  const contentOutput = path.join(collectionOutput, "content");
  await mkdir(contentOutput, { recursive: true });

  const catalog = [];
  const loaders = [];
  for (const song of metadata.songs) {
    const sourcePath = path.join(sourceRoot, song.sourceFile);
    const source = await readFile(sourcePath, "utf8");
    const cleanSource = removeSearchTags(source);
    const { knMarkdown, enMarkdown, titleEn } = splitSongContent(cleanSource, song);

    const html = renderMarkdown(cleanSource);
    const htmlKn = renderMarkdown(knMarkdown);
    const htmlEn = renderMarkdown(enMarkdown);

    const contentFile = `content/${song.id}.html`;
    await writeFile(path.join(collectionOutput, contentFile), html, "utf8");
    await writeFile(path.join(collectionOutput, `content/${song.id}-kn.html`), htmlKn, "utf8");
    await writeFile(path.join(collectionOutput, `content/${song.id}-en.html`), htmlEn, "utf8");
    await writeFile(
      path.join(collectionOutput, `content/${song.id}.ts`),
      `export const html: string = ${JSON.stringify(html)};\n` +
        `export const htmlKn: string = ${JSON.stringify(htmlKn)};\n` +
        `export const htmlEn: string = ${JSON.stringify(htmlEn)};\n`,
      "utf8",
    );
    loaders.push(`  ${JSON.stringify(song.id)}: () => import("./content/${song.id}"),`);

    catalog.push({
      id: song.id,
      title: song.title,
      titleKn: song.title,
      titleEn,
      kruti: song.kruti ?? "",
      krutiKn: song["kruti-kn"] ?? "",
      ankita: song.ankita ?? "",
      ankitaKn: song["ankita-kn"] ?? "",
      searchText: buildSearchText({ ...song, titleEn }),
      contentFile,
    });
  }

  const searchIndex = new MiniSearch({
    idField: "__search_id",
    fields: [
      "title",
      "titleKn",
      "titleEn",
      "kruti",
      "krutiKn",
      "ankita",
      "ankitaKn",
      "searchTags",
      "searchText",
    ],
    extractField: (item, field) => {
      if (field === "searchTags" && Array.isArray(item.searchTags)) {
        return item.searchTags.join(" ");
      }
      const val = item[field];
      return val != null ? String(val) : "";
    },
    searchOptions: {
      boost: {
        title: 3,
        titleKn: 3,
        titleEn: 3,
        ankita: 2,
        ankitaKn: 2,
        kruti: 1.5,
        krutiKn: 1.5,
      },
      prefix: true,
      fuzzy: (term) => (term.length > 3 ? 0.2 : false),
      combineWith: "AND",
    },
  });

  const docs = catalog.map((item, idx) => ({ ...item, __search_id: idx }));
  searchIndex.addAll(docs);

  const serialized = JSON.stringify(searchIndex.toJSON());
  const compressed = gzipSync(serialized).toString("base64");

  const searchIndexCode = `// Generated by build/build-bhakti-content.mjs — do not edit
export const compressedBhaktiSearchIndex = ${JSON.stringify(compressed)};
`;

  const loadersCode = `// Generated by build/build-bhakti-content.mjs — do not edit
export interface BhaktiSongModule {
  html: string;
  htmlKn?: string;
  htmlEn?: string;
}

export const loadBhaktiSearchIndex = () => import("./search-index");

export const bhaktiContentLoaders: Record<string, () => Promise<BhaktiSongModule>> = {
${loaders.join("\n")}
};
`;

  await writeFile(path.join(collectionOutput, "search-index.ts"), searchIndexCode, "utf8");
  await writeFile(path.join(collectionOutput, "loaders.ts"), loadersCode, "utf8");
  await writeFile(
    path.join(collectionOutput, "index.json"),
    `${JSON.stringify({ schemaVersion: metadata.schemaVersion, items: catalog })}\n`,
    "utf8",
  );

  return catalog.length;
}

await Promise.all([
  rm(path.join(dataRoot, collection.id), { recursive: true, force: true }),
  rm(previousCollectionRoot, { recursive: true, force: true }),
  rm(previousGeneratedRoot, { recursive: true, force: true }),
  rm(legacyGeneratedRoot, { recursive: true, force: true }),
  rm(legacyDataRoot, { recursive: true, force: true }),
]);
await mkdir(dataRoot, { recursive: true });

const itemCount = await buildCollection(collection);
console.log(`Built ${itemCount} items for ${collection.id}.`);

