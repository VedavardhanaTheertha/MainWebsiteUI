import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const projectRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const environmentName = process.env.SITE_ENV || "dev";
const settingsEnvironment = environmentName === "local" ? "dev" : environmentName;
const outputPath = path.join(projectRoot, "src", "gen", "media", "albums.ts");

const languageContent = JSON.parse(
  await readFile(path.join(projectRoot, "content", "languages", "en.json"), "utf8"),
);
const albums = languageContent.media?.albums;
if (!Array.isArray(albums) || albums.length === 0) {
  throw new Error("content/languages/en.json must define a non-empty media.albums array.");
}

const albumIds = new Set();
for (const album of albums) {
  if (typeof album?.id !== "string" || !album.id.trim()) {
    throw new Error("Every media.albums record must define a non-empty id.");
  }
  if (albumIds.has(album.id)) {
    throw new Error(`content/languages/en.json contains duplicate media album "${album.id}".`);
  }
  albumIds.add(album.id);
}

async function loadConfiguredIds(filename, field, nestedInSections = false) {
  const sourceName = `settings/${settingsEnvironment}/${filename}.json`;
  const parsed = JSON.parse(await readFile(path.join(projectRoot, sourceName), "utf8"));
  const configuredIds = nestedInSections ? parsed?.sections?.[field] : parsed?.[field];
  if (!Array.isArray(configuredIds) || configuredIds.length === 0) {
    throw new Error(`${sourceName} must define a non-empty ${field} array.`);
  }

  const seen = new Set();
  for (const id of configuredIds) {
    if (typeof id !== "string" || !albumIds.has(id)) {
      throw new Error(`${sourceName} references unknown album "${id}".`);
    }
    if (seen.has(id)) {
      throw new Error(`${sourceName} contains duplicate album "${id}".`);
    }
    seen.add(id);
  }
  return configuredIds;
}

const [topAlbumIds, recentAlbumIds] = await Promise.all([
  loadConfiguredIds("toplibrary", "album", true),
  loadConfiguredIds("recentalbums", "album_ids"),
]);

await mkdir(path.dirname(outputPath), { recursive: true });
await writeFile(
  outputPath,
  `// Generated by build/build-media-albums.mjs — do not edit\n` +
    `export const topAlbumIds = ${JSON.stringify(topAlbumIds)} as const;\n` +
    `export const recentAlbumIds = ${JSON.stringify(recentAlbumIds)} as const;\n`,
  "utf8",
);

console.log(
  `Built media album settings (${topAlbumIds.length} top, ${recentAlbumIds.length} recent).`,
);
