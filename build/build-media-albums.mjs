import { mkdir, writeFile } from "node:fs/promises";
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { validateMedia } from "./media-schema.mjs";
import { holdWorkspaceLock } from "./workspace-lock.mjs";
import { loadAlbums, loadAlbumConfig, computeAlbumRankings } from "./album-content.mjs";
import { discoverLanguageContent } from "./language-content.mjs";

holdWorkspaceLock("media generation");
const projectRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const outputPath = path.join(projectRoot, "src", "gen", "media", "albums.ts");
const dataOutputPath = path.join(projectRoot, "src", "gen", "media", "data.ts");

const albums = loadAlbums(projectRoot);
const albumConfig = loadAlbumConfig(projectRoot);
const { codes: languageCodes } = discoverLanguageContent(projectRoot);

// Validate albums for each language
for (const code of languageCodes) {
  const localizedAlbums = albums.map((album) => ({
    id: album.id,
    title: album.title[code] ?? album.title.en,
    description: album.description[code] ?? album.description.en,
    cover: album.cover,
    tags: album.tags[code] ?? album.tags.en,
    date: album.date,
    event: album.event,
    items: album.items,
  }));
  validateMedia({ albums: localizedAlbums }, `library/albums (lang: ${code})`);
}

const { recentAlbumIds, topAlbumIds } = computeAlbumRankings(albums, albumConfig);

await mkdir(path.dirname(outputPath), { recursive: true });

await writeFile(
  outputPath,
  `// Generated by build/build-media-albums.mjs — do not edit\n` +
    `export const topAlbumIds = ${JSON.stringify(topAlbumIds)} as const;\n` +
    `export const recentAlbumIds = ${JSON.stringify(recentAlbumIds)} as const;\n`,
  "utf8",
);

await writeFile(
  dataOutputPath,
  `// Generated by build/build-media-albums.mjs — do not edit\n` +
    `export const albumsCatalog = ${JSON.stringify(albums, null, 2)} as const;\n`,
  "utf8",
);

// Synchronize settings/{dev,prod}/toplibrary.json to prevent config drift
for (const env of ["dev", "prod"]) {
  const topLibPath = path.join(projectRoot, "settings", env, "toplibrary.json");
  if (existsSync(topLibPath)) {
    try {
      const topLib = JSON.parse(readFileSync(topLibPath, "utf8"));
      if (topLib?.sections) {
        topLib.sections.album = topAlbumIds;
        writeFileSync(topLibPath, JSON.stringify(topLib, null, 2) + "\n", "utf8");
      }
    } catch {
      // Ignore if toplibrary.json cannot be parsed
    }
  }
}

console.log(
  `Built media album settings (${topAlbumIds.length} top, ${recentAlbumIds.length} recent from ${albums.length} albums).`,
);
