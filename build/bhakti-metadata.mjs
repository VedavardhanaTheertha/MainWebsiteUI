export function compositionTypeFromMetadata(song) {
  if (song.compositionType === undefined) return "";
  if (typeof song.compositionType !== "string" || !song.compositionType.trim()) {
    throw new Error(`${song.sourceFile ?? song.id}: compositionType must be a non-empty string.`);
  }

  return song.compositionType.trim();
}

export function bhaktiSummaryModule(itemCount) {
  if (!Number.isSafeInteger(itemCount) || itemCount < 0) {
    throw new Error("Bhakti item count must be a non-negative safe integer.");
  }
  return `// Generated by build/build-bhakti-content.mjs — do not edit\nexport const bhaktiItemCount: number = ${itemCount};\n`;
}
