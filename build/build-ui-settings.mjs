import { mkdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { loadAnnouncementSettings, loadUiElements, loadUiSettings } from "./ui-settings.mjs";
import { uiFieldDefinitions } from "./ui-settings-schema.mjs";
import { searchSettings } from "./search-config.mjs";
import { loadActionSettings } from "./action-settings.mjs";
import { loadCommonSettings } from "./common-settings.mjs";
import { holdWorkspaceLock } from "./workspace-lock.mjs";

holdWorkspaceLock("settings generation");
const projectRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const outputPath = path.join(projectRoot, "src", "gen", "settings", "ui-elements.ts");
const settings = loadUiSettings();
const announcementSettings = loadAnnouncementSettings();
const envName = (process.env.SITE_ENV || "dev") === "prod" ? "prod" : "dev";
const commonSettings = loadCommonSettings(envName, projectRoot);
loadActionSettings();

await mkdir(path.dirname(outputPath), { recursive: true });
await writeFile(
  outputPath,
  `// Generated by build/build-ui-settings.mjs — do not edit\n` +
    `import type { UiElements, UiSettings, UiFieldDefinition } from "@/lib/ui-settings-types";\n` +
    `export const uiElementDefaults: UiElements = ${JSON.stringify(loadUiElements())};\n` +
    `export const uiSettingsDefaults: UiSettings = ${JSON.stringify(settings)};\n` +
    `export const uiFields: UiFieldDefinition[] = ${JSON.stringify(uiFieldDefinitions)};\n` +
    Object.entries(settings).map(([name, value]) =>
      `export const ${name} = ${JSON.stringify(value)} as const;\n`,
    ).join(""),
  "utf8",
);

await writeFile(
  path.join(path.dirname(outputPath), "announcements.ts"),
  `// Generated by build/build-ui-settings.mjs — do not edit\n` +
    `import type { AnnouncementSettings } from "@/lib/ui-settings";\n` +
    `export const announcementSettings: AnnouncementSettings = ${JSON.stringify(announcementSettings)};\n`,
  "utf8",
);
await writeFile(
  path.join(path.dirname(outputPath), "search.ts"),
  `// Generated by build/build-ui-settings.mjs — do not edit\n` +
    `export const searchSettings = ${JSON.stringify(searchSettings)} as const;\n`,
  "utf8",
);
await writeFile(
  path.join(path.dirname(outputPath), "common.ts"),
  `// Generated by build/build-ui-settings.mjs — do not edit\n` +
    `import type { CommonSettings } from "@/lib/common-settings-types";\n` +
    `export const commonSettings: CommonSettings = ${JSON.stringify(commonSettings)};\n`,
  "utf8",
);
console.log("Built shared UI, announcement, search, and common settings.");
