import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const projectRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const sourceName = "settings/ui_elements.json";
const sourcePath = path.join(projectRoot, sourceName);
const outputPath = path.join(projectRoot, "src", "gen", "settings", "ui-elements.ts");

function requirePositiveInteger(value, field) {
  if (!Number.isInteger(value) || value < 1) {
    throw new Error(`${sourceName} ${field} must be a positive integer.`);
  }
  return value;
}

const parsed = JSON.parse(await readFile(sourcePath, "utf8"));
const collections = parsed?.collections;
if (!collections || typeof collections !== "object" || Array.isArray(collections)) {
  throw new Error(`${sourceName} must define a collections object.`);
}

const pagination = {
  initialVisible: requirePositiveInteger(
    collections.initialVisible,
    "collections.initialVisible",
  ),
  loadIncrement: requirePositiveInteger(
    collections.loadIncrement,
    "collections.loadIncrement",
  ),
};

const autoScroll = parsed?.autoScroll;
if (!autoScroll || typeof autoScroll !== "object" || Array.isArray(autoScroll)) {
  throw new Error(`${sourceName} must define an autoScroll object.`);
}
if (!Number.isFinite(autoScroll.pixelsPerSecond) || autoScroll.pixelsPerSecond <= 0) {
  throw new Error(`${sourceName} autoScroll.pixelsPerSecond must be a positive finite number.`);
}
const railAutoScroll = {
  pixelsPerSecond: autoScroll.pixelsPerSecond,
  returnDurationMs: requirePositiveInteger(autoScroll.returnDurationMs, "autoScroll.returnDurationMs"),
};

await mkdir(path.dirname(outputPath), { recursive: true });
await writeFile(
  outputPath,
  `// Generated by build/build-ui-settings.mjs — do not edit\n` +
    `export const collectionPagination = ${JSON.stringify(pagination)} as const;\n` +
    `export const railAutoScroll = ${JSON.stringify(railAutoScroll)} as const;\n`,
  "utf8",
);

console.log(
  `Built shared UI settings ` +
    `(initial: ${pagination.initialVisible}, increment: ${pagination.loadIncrement}, ` +
    `scroll: ${railAutoScroll.pixelsPerSecond}px/s, return: ${railAutoScroll.returnDurationMs}ms).`,
);
