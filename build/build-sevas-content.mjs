import { readdir, readFile, writeFile, mkdir } from "node:fs/promises";
import { existsSync, statSync } from "node:fs";
import { gzipSync } from "node:zlib";
import path from "node:path";
import { fileURLToPath } from "node:url";
import yaml from "js-yaml";
import MiniSearch from "minisearch";

const projectRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const sevasSourceDir = path.join(projectRoot, "library", "sevas");
const outputDir = path.join(projectRoot, "src", "gen", "sevas");

await mkdir(outputDir, { recursive: true });

if (!existsSync(sevasSourceDir)) {
  throw new Error(`Sevas directory not found at: ${sevasSourceDir}`);
}

const entries = await readdir(sevasSourceDir);
const mdFiles = entries
  .filter((f) => f.endsWith(".md") && statSync(path.join(sevasSourceDir, f)).isFile())
  .sort();

console.log(`Found ${mdFiles.length} seva files in library/sevas`);

const categoryMap = {
  "krishna-sannidhi": "Krishna Sannidhi",
  "mukhyaprana-sannidhi": "Mukhyaprana Sannidhi",
  "garuda-sannidhi": "Garuda Deva Sannidhi",
  "bhojana-shala-mukhyaprana": "Bhojana Shala",
  "bhageerathi-sannidhi": "Bhageerathi",
  "navagraha-sannidhi": "Navagraha",
  "subrahmanya-sannidhi": "Subrahmanya",
  "special-sevas": "Special",
  "other-sevas": "Other",
};

const categoryIconMap = {
  "Krishna Sannidhi": "🌸",
  "Mukhyaprana Sannidhi": "🚩",
  "Garuda Deva Sannidhi": "🦅",
  "Bhojana Shala": "🍛",
  "Bhageerathi": "🌊",
  "Navagraha": "☀️",
  "Subrahmanya": "🐍",
  "Special": "✨",
  "Other": "🪔",
};

const parsedSevas = [];

for (const file of mdFiles) {
  const fullPath = path.join(sevasSourceDir, file);
  const raw = await readFile(fullPath, "utf8");
  const fmMatch = raw.match(/^---\r?\n([\s\S]*?)\r?\n---\r?\n([\s\S]*)$/);
  if (!fmMatch) continue;

  const fm = yaml.load(fmMatch[1]) || {};
  const code = Number(fm.code) || 0;
  const rawCategoryCode = fm.category?.code || "other-sevas";
  const categoryName = categoryMap[rawCategoryCode] || "Other";
  const icon = categoryIconMap[categoryName] || "🪔";

  parsedSevas.push({
    id: fm.id || file.replace(/\.md$/, ""),
    code,
    entity_id: Number(fm.entity_id) || 3,
    event_id: Number(fm.event_id) || 4,
    name: fm.title?.en || fm.name?.en || file.replace(/^\d+-/, "").replace(/\.md$/, ""),
    nameKn: fm.title?.kn || fm.name?.kn || "",
    category: categoryName,
    categoryKn: fm.category?.kn || categoryName,
    categoryCode: rawCategoryCode,
    categoryOriginalEn: fm.category?.en || categoryName,
    sannidhi: fm.sannidhi?.en || "",
    sannidhiKn: fm.sannidhi?.kn || "",
    deity: fm.deity?.en || "",
    deityKn: fm.deity?.kn || "",
    location: fm.location?.en || "Shri Krishna Matha, Udupi",
    locationKn: fm.location?.kn || "ಶ್ರೀ ಕೃಷ್ಣ ಮಠ, ಉಡುಪಿ",
    price: Number(fm.amount) || 0,
    formattedPrice: fm.formatted_amount?.en || (Number(fm.amount) > 0 ? `₹${Number(fm.amount).toLocaleString("en-IN")}` : "Any Amount"),
    formattedPriceKn: fm.formatted_amount?.kn || (Number(fm.amount) > 0 ? `₹${Number(fm.amount).toLocaleString("en-IN")}` : "ಕಾಣಿಕೆ"),
    significance: fm.significance?.en || fm.description?.en || "",
    significanceKn: fm.significance?.kn || fm.description?.kn || "",
    description: fm.description?.en || "",
    descriptionKn: fm.description?.kn || "",
    bookingUrl: fm.booking_url || `https://pay.shiroormatha.org/?entity_id=3&event_id=4&seva_id=${code}`,
    icon,
    highlight: Number(fm.highlight) || 0,
    isSpecial: categoryName === "Special" || Boolean(fm.is_popular) || Number(fm.amount) >= 100000,
    isPopular: Boolean(fm.is_popular),
  });
}

parsedSevas.sort((a, b) => a.code - b.code);

// Write src/data/sevas.ts with canonical data
const sevasTsContent = `// Canonical sevas data parsed from library/sevas/*.md
// Generated by build/build-sevas-content.mjs — do not edit directly.

export type SevaCategory =
  | "Krishna Sannidhi"
  | "Mukhyaprana Sannidhi"
  | "Garuda Deva Sannidhi"
  | "Bhojana Shala"
  | "Bhageerathi"
  | "Navagraha"
  | "Subrahmanya"
  | "Special"
  | "Other";

export interface Seva {
  id: string;
  code: number;
  entity_id?: number;
  event_id?: number;
  name: string;
  nameKn: string;
  category: SevaCategory;
  categoryKn: string;
  categoryCode?: string;
  categoryOriginalEn?: string;
  sannidhi: string;
  sannidhiKn: string;
  deity: string;
  deityKn: string;
  location: string;
  locationKn: string;
  significance: string;
  significanceKn: string;
  description: string;
  descriptionKn: string;
  price: number;
  formattedPrice: string;
  formattedPriceKn: string;
  bookingUrl: string;
  icon: string;
  isSpecial?: boolean;
  isPopular?: boolean;
  highlight?: number;
}

export const sevas: Seva[] = ${JSON.stringify(parsedSevas, null, 2)};
`;

await writeFile(path.join(projectRoot, "src", "data", "sevas.ts"), sevasTsContent, "utf8");
console.log(`Updated src/data/sevas.ts with ${parsedSevas.length} canonical sevas.`);

// Prepare MiniSearch documents
const docs = parsedSevas.map((s, idx) => ({
  __search_id: idx,
  id: s.id,
  code: String(s.code),
  name: s.nameKn ? `${s.name} ${s.nameKn}` : s.name,
  significance: s.significanceKn ? `${s.significance} ${s.significanceKn}` : s.significance,
  category: s.categoryKn ? `${s.category} ${s.categoryKn}` : s.category,
}));

const miniSearch = new MiniSearch({
  idField: "__search_id",
  fields: ["name", "significance", "category"],
  searchOptions: {
    boost: { name: 2, category: 1.5, significance: 1 },
    prefix: true,
    fuzzy: (term) => (term.length > 3 ? 0.2 : false),
    combineWith: "AND",
  },
});

miniSearch.addAll(docs);

const serialized = JSON.stringify(miniSearch.toJSON());
const compressed = gzipSync(serialized).toString("base64");

const searchIndexCode = `// Generated by build/build-sevas-content.mjs — do not edit
export const compressedSevasSearchIndex = ${JSON.stringify(compressed)};
`;

const loadersCode = `// Generated by build/build-sevas-content.mjs — do not edit
export const loadSevasSearchIndex = () => import("./search-index");
`;

// Localized data for components
const sevasByLanguage = {
  en: parsedSevas.map((s) => ({
    id: s.id,
    code: s.code,
    name: s.name,
    category: s.category,
    sannidhi: s.sannidhi,
    deity: s.deity,
    location: s.location,
    significance: s.significance,
    description: s.description,
    price: s.price,
    formattedPrice: s.formattedPrice,
    bookingUrl: s.bookingUrl,
    icon: s.icon,
    isSpecial: s.isSpecial,
    isPopular: s.isPopular,
  })),
  kn: parsedSevas.map((s) => ({
    id: s.id,
    code: s.code,
    name: s.nameKn || s.name,
    category: s.categoryKn || s.category,
    sannidhi: s.sannidhiKn || s.sannidhi,
    deity: s.deityKn || s.deity,
    location: s.locationKn || s.location,
    significance: s.significanceKn || s.significance,
    description: s.descriptionKn || s.description,
    price: s.price,
    formattedPrice: s.formattedPriceKn || s.formattedPrice,
    bookingUrl: s.bookingUrl,
    icon: s.icon,
    isSpecial: s.isSpecial,
    isPopular: s.isPopular,
  })),
};

const dataCode = `// Generated by build/build-sevas-content.mjs — do not edit
export const sevasByLanguage = ${JSON.stringify(sevasByLanguage, null, 2)};
export const sevas = ${JSON.stringify(parsedSevas, null, 2)};
`;

await writeFile(path.join(outputDir, "search-index.ts"), searchIndexCode, "utf8");
await writeFile(path.join(outputDir, "loaders.ts"), loadersCode, "utf8");
await writeFile(path.join(outputDir, "data.ts"), dataCode, "utf8");

